import starlight from "@astrojs/starlight"
import type { StarlightExpressiveCodeOptions } from "@astrojs/starlight/expressive-code"
import tailwindcss from "@tailwindcss/vite"
import { inkRampSyntaxTheme } from "@workspace/ui/lib/syntax-theme"
import { defineConfig } from "astro/config"

import {
  EXTERNAL_LINK_ATTRS,
  GITHUB_REPO_URL,
  SKILLS_REPO_URL,
} from "./src/lib/links"
import { RELEASES_DIRECTORY } from "./src/lib/release-pages"

// No terminal frame: its mask-painted dots escape site.css's radius reset.
const CODE_BLOCK_DEFAULTS = { frame: "none" } as const

/**
 * The theme lives in @workspace/ui. Both slots are light: Starlight requires a
 * pair and hardcodes `data-theme="dark"` without JS. Expressive Code caches its
 * output; if an edit seems to do nothing, `rm -rf dist .astro node_modules/.astro`.
 */
type SyntaxTheme = NonNullable<StarlightExpressiveCodeOptions["themes"]>[number]

const SYNTAX_THEMES: SyntaxTheme[] = [
  inkRampSyntaxTheme("agents-inc-dark", "dark"),
  inkRampSyntaxTheme("agents-inc", "light"),
]

// No React integration on purpose: the site needs only the design system's CSS tokens.
export default defineConfig({
  // Sitemap and canonical URLs need the origin. No `base`: this build owns the apex.
  site: "https://agentsinc.sh",

  output: "static",

  // Starlight defaults to prefetchAll, which injects script into every page.
  prefetch: false,

  vite: {
    plugins: [tailwindcss()],
  },

  integrations: [
    starlight({
      title: "Agents Inc",

      // Starlight's 404 would claim /404 site-wide; src/pages/404.astro replaces it.
      disable404Route: true,

      // `seti:*` icons are file-type glyphs, hence `puzzle`.
      social: [
        { icon: "github", label: "GitHub", href: GITHUB_REPO_URL },
        { icon: "puzzle", label: "Skills", href: SKILLS_REPO_URL },
      ],

      expressiveCode: {
        defaultProps: CODE_BLOCK_DEFAULTS,
        themes: SYNTAX_THEMES,

        // Block chrome follows site.css's `--sl-color-*` mapping.
        useStarlightUiThemeColors: true,

        // One light theme, so no dark copy of every colour.
        useStarlightDarkModeSwitch: false,

        // 0 ships the palette as declared; the default rewrites colours below 5.5 contrast.
        minSyntaxHighlightingColorContrast: 0,
      },

      customCss: ["./src/styles/site.css"],

      routeMiddleware: "./src/route-data.ts",

      components: {
        ThemeProvider: "./src/components/theme-provider.astro",
        ThemeSelect: "./src/components/theme-select.astro",

        Head: "./src/components/head.astro",
      },

      // The `docs/` prefix is deliberate: content nests one level deeper to serve under /docs.
      sidebar: [
        {
          label: "Start here",
          items: [
            { slug: "docs/why" },
            { slug: "docs/ways-in" },
            { slug: "docs/quickstart" },
            { slug: "docs/cli-or-web" },
          ],
        },
        {
          label: "Concepts",
          items: [
            { slug: "docs/concepts/skills" },
            { slug: "docs/concepts/sub-agents" },
            { slug: "docs/concepts/stacks" },
            { slug: "docs/concepts/install-modes" },
            { slug: "docs/concepts/scopes" },
          ],
        },
        // Autogenerated groups nest inside `items`; each page's `sidebar.order`
        // frontmatter sets the order.
        {
          label: "Guides",
          items: [{ autogenerate: { directory: "docs/guides" } }],
        },

        {
          label: "Configuration",
          items: [{ autogenerate: { directory: "docs/configuration" } }],
        },
        {
          label: "The editor",
          items: [{ autogenerate: { directory: "docs/editor" } }],
        },
        {
          label: "Recipes",
          items: [{ autogenerate: { directory: "docs/recipes" } }],
        },
        {
          label: "Troubleshooting",
          items: [{ autogenerate: { directory: "docs/troubleshooting" } }],
        },
        {
          label: "Reference",
          items: [{ autogenerate: { directory: "docs/reference" } }],
        },
        // Collapsed: it lists every release.
        {
          label: "Releases",
          collapsed: true,
          items: [{ autogenerate: { directory: RELEASES_DIRECTORY } }],
        },
        {
          label: "Resources",
          items: [
            { slug: "docs/resources" },
            {
              label: "Skills repository",
              link: SKILLS_REPO_URL,
              attrs: EXTERNAL_LINK_ATTRS,
            },
            {
              label: "GitHub repository",
              link: GITHUB_REPO_URL,
              attrs: EXTERNAL_LINK_ATTRS,
            },
          ],
        },
      ],
    }),
  ],
})

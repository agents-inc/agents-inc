import { baseConfig, typeCheckedConfig } from "@workspace/eslint-config/base"
import { defineConfig, globalIgnores } from "eslint/config"

// baseConfig only matches `**/*.{ts,tsx}`, which here is astro.config.ts and
// src/content.config.ts. `.astro` files are deliberately not linted: doing so
// needs eslint-plugin-astro and its own parser, and there is no React config
// to inherit here — this workspace has no React at all, on purpose. See the
// note at the top of astro.config.ts.
export default defineConfig([
  ...baseConfig,
  ...typeCheckedConfig(import.meta.dirname),
  // Astro's generated types and content-collection cache. Regenerated by
  // `astro sync`, and not ours to lint.
  globalIgnores([".astro/**"]),
])

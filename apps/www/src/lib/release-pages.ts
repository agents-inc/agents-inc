import { readdir, readFile } from "node:fs/promises"
import { basename } from "node:path"

import type { Loader, LoaderContext } from "astro/loaders"

import { GITHUB_REPO_URL } from "./links"

// Read from the notes at build time, so no committed copy can drift from them.

export const RELEASES_DIRECTORY = "docs/releases"

const NOTES_FROM_SITE_ROOT = "../../packages/cli/changelogs/"

const NOTES_ON_GITHUB = `${GITHUB_REPO_URL}/blob/main/packages/cli/changelogs/`

const NOTES_FILE = /^\d+\.\d+\.\d+\.md$/

const HEADING_MARK = "# "

// Numeric, so 0.175.0 sorts above 0.32.0.
const VERSION_ORDER = new Intl.Collator("en", { numeric: true })

// Written against the notes' place in the repository: no scheme, not rooted, not a fragment.
const RELATIVE_HREF = /href="((?![a-z][a-z\d+.-]*:|[/#])[^"]*)"/gi

const SIBLING_NOTES = /^(?:\.\/)?\d+\.\d+\.\d+\.md$/

type Release = { version: string; title: string; body: string }

export function withReleasePages(docs: Loader): Loader {
  return {
    name: "docs-with-release-pages",
    load: async (context) => {
      await docs.load(context)
      const releases = await readReleasesNewestFirst(
        new URL(NOTES_FROM_SITE_ROOT, context.config.root)
      )
      await Promise.all(
        releases.map((release, position) =>
          storeReleasePage(context, release, position)
        )
      )
    },
  }
}

async function readReleasesNewestFirst(notesDir: URL): Promise<Release[]> {
  const versions = (await readdir(notesDir))
    .filter((file) => NOTES_FILE.test(file))
    .map((file) => basename(file, ".md"))
    .sort((a, b) => VERSION_ORDER.compare(b, a))

  return Promise.all(versions.map((version) => readRelease(notesDir, version)))
}

async function readRelease(notesDir: URL, version: string): Promise<Release> {
  const notes = await readFile(new URL(`${version}.md`, notesDir), "utf8")
  return releaseFrom(version, notes)
}

// Starlight renders the title as the page's <h1>, so the body starts below the heading.
function releaseFrom(version: string, notes: string): Release {
  const [heading = "", ...bodyLines] = notes.split("\n")
  if (!heading.startsWith(HEADING_MARK)) {
    throw new Error(
      `${NOTES_FROM_SITE_ROOT}${version}.md opens with "${heading}", not the "${HEADING_MARK}" heading its release page takes as its title`
    )
  }

  return {
    version,
    title: heading.slice(HEADING_MARK.length).trim(),
    body: bodyLines.join("\n"),
  }
}

async function storeReleasePage(
  context: LoaderContext,
  release: Release,
  sidebarOrder: number
): Promise<void> {
  const id = `${RELEASES_DIRECTORY}/${release.version}`
  const [data, rendered] = await Promise.all([
    context.parseData({
      id,
      data: {
        title: release.title,
        sidebar: { label: release.version, order: sidebarOrder },
        pagefind: false,
      },
    }),
    context.renderMarkdown(release.body),
  ])

  context.store.set({
    id,
    data,
    body: release.body,
    rendered: { ...rendered, html: resolveRelativeLinks(rendered.html) },
    // Starlight's autogenerated sidebar places an entry by this path and crashes without one.
    filePath: `src/content/docs/${id}.md`,
  })
}

// The rendered HTML, not the Markdown: a code span may hold link syntax too.
function resolveRelativeLinks(html: string): string {
  return html.replace(
    RELATIVE_HREF,
    (_attribute, href: string) => `href="${siteHrefOf(href)}"`
  )
}

function siteHrefOf(relativeHref: string): string {
  return SIBLING_NOTES.test(relativeHref)
    ? `/${RELEASES_DIRECTORY}/${basename(relativeHref, ".md")}/`
    : new URL(relativeHref, NOTES_ON_GITHUB).href
}

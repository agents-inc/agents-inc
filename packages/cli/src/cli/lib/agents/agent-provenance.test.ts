import path from "node:path";
import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

import { renderAgent } from "@workspace/compile/agent-source";

import { createLiquidEngine } from "../compiler.js";
import { createMockCompiledAgentData } from "../__tests__/factories/agent-factories.js";
import {
  cliVersion,
  hasProvenanceMarker,
  provenanceMarker,
  stampProvenanceMarker,
} from "./agent-provenance";

const CLI_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../../..");

const COMPILED_AGENT = [
  "---",
  "name: web-developer",
  "description: A test agent",
  "---",
  "",
  "# Web Developer Agent",
  "",
  "body",
].join("\n");

const HAND_WRITTEN_AGENT = ["---", "name: my-custom-agent", "---", "", "# Mine"].join("\n");

const BODY_WITHOUT_FRONTMATTER = ["# Mine", "", "body"].join("\n");

/**
 * The marker releases up to 0.162.0 wrote, as a literal so it cannot drift with today's builder.
 */
const VERSIONED_MARKER_A_PAST_RELEASE_WROTE =
  "<!-- Generated by agents-inc v0.162.0 — do not edit; compile rewrites this file -->";

describe("agent provenance marker", () => {
  /** The marker is the first cacheable byte of every sub-agent prompt, so it carries no version. */
  it("spells the same bytes whatever version stamped it", async () => {
    const pkg = JSON.parse(await readFile(path.join(CLI_ROOT, "package.json"), "utf8")) as {
      version: string;
    };

    expect(await cliVersion()).toBe(pkg.version);
    expect(
      provenanceMarker(),
      "the marker names a version again — every release now rewrites the first cacheable byte of all eighteen agents",
    ).not.toContain(pkg.version);
  });

  /** Two versions render byte-identical up to `<system-reminder>`, each still carrying its own. */
  it("confines a version difference to the trailing <system-reminder> block", async () => {
    const engine = await createLiquidEngine();
    const data = createMockCompiledAgentData();

    const renderedAtV1 = await renderAgent(engine, data, "9.1.0");
    const renderedAtV2 = await renderAgent(engine, data, "9.2.0");

    const volatileBlockStart = "<system-reminder>";
    const prefix = (rendered: string) => rendered.slice(0, rendered.indexOf(volatileBlockStart));

    expect(
      prefix(renderedAtV1),
      "a version bump changed a byte above the trailing block, so it rewrites the cacheable prefix of every compiled agent again",
    ).toBe(prefix(renderedAtV2));
    expect(renderedAtV1).toContain("Compiled by 9.1.0.");
    expect(renderedAtV2).toContain("Compiled by 9.2.0.");
  });

  it("goes on the first line after the frontmatter", () => {
    expect(stampProvenanceMarker(COMPILED_AGENT)).toBe(
      [
        "---",
        "name: web-developer",
        "description: A test agent",
        "---",
        provenanceMarker(),
        "",
        "# Web Developer Agent",
        "",
        "body",
      ].join("\n"),
    );
  });

  it("goes on the first line when there is no frontmatter to follow", () => {
    expect(stampProvenanceMarker(BODY_WITHOUT_FRONTMATTER)).toBe(
      [provenanceMarker(), ...BODY_WITHOUT_FRONTMATTER.split("\n")].join("\n"),
    );
  });

  it("is a fixed point — stamping already-stamped content changes nothing", () => {
    const stamped = stampProvenanceMarker(COMPILED_AGENT);

    expect(stampProvenanceMarker(stamped)).toBe(stamped);
  });

  /** Agents on disk carry the versioned line; a recompile must leave exactly one marker. */
  it("replaces the versioned marker a past release wrote rather than stacking beside it", () => {
    const stampedByAPastRelease = [
      "---",
      "name: web-developer",
      "description: A test agent",
      "---",
      VERSIONED_MARKER_A_PAST_RELEASE_WROTE,
      "",
      "# Web Developer Agent",
      "",
      "body",
    ].join("\n");

    expect(stampProvenanceMarker(stampedByAPastRelease)).toBe(
      stampProvenanceMarker(COMPILED_AGENT),
    );
  });

  it("recognises its own marker and the versioned one a past release wrote", () => {
    expect(hasProvenanceMarker(stampProvenanceMarker(COMPILED_AGENT))).toBe(true);
    expect(
      hasProvenanceMarker(
        ["---", "name: a", "---", VERSIONED_MARKER_A_PAST_RELEASE_WROTE, "", "body"].join("\n"),
      ),
      "an agent a past release compiled is no longer recognised as this CLI's own — uninstall would leave it behind",
    ).toBe(true);
  });

  it("does not recognise an agent nothing stamped", () => {
    expect(hasProvenanceMarker(HAND_WRITTEN_AGENT)).toBe(false);
    expect(hasProvenanceMarker(BODY_WITHOUT_FRONTMATTER)).toBe(false);
  });

  /**
   * The marker's position is its contract: a body quoting the line was not compiled by this CLI.
   */
  it("does not recognise the marker quoted inside the body", () => {
    const quoting = [
      "---",
      "name: my-custom-agent",
      "---",
      "",
      "# Mine",
      "",
      `Compiled agents open with: ${provenanceMarker()}`,
    ].join("\n");

    expect(hasProvenanceMarker(quoting)).toBe(false);
  });
});

/**
 * What an install writes, as data: a configuration and the exact bytes both renderers must produce.
 * Configurations are written out, not built from a factory, so nothing stands between them.
 *
 * These reach no scenario; `config-types-source.test.ts` pins their bytes and formatting instead:
 * - the sectioned `// Custom` / `// Marketplace` union needs a custom skill, agent or domain, and
 *   a scenario's ids are the built-in catalogue's;
 * - `generateProjectConfigTypesSource` imports from a path under the user's home folder, so its
 *   bytes differ per machine.
 * That none is reached, from this package (prints nothing):
 * grep -nE "^  // Custom$|^  SkillId as GlobalSkillId,$" src/contract/emission-scenarios.ts
 */


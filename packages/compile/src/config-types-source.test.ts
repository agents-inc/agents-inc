describe("the types of a whole catalogue, with no config to narrow them", () => {
  it("sorts every union, sections off an id no catalogue declares, and leaves undomained categories out of Domain", () => {
    expect(renderWholeCatalogue()).toContain(WHOLE_CATALOGUE_ALIASES)
  })

  it("keys the stack by every category holding a skill, never by local, and unwraps an exclusive one", () => {
    expect(renderWholeCatalogue()).toContain(WHOLE_CATALOGUE_STACK)
  })
})

describe("the types a config narrows", () => {
  it("sections custom skills, agents, domains and categories from the marketplace's", () => {
    expect(renderCustomConfig()).toContain(CUSTOM_CONFIG_ALIASES)
  })

  it("keys the stack by the config's own categories", () => {
    expect(renderCustomConfig()).toContain(CUSTOM_CONFIG_STACK)
  })

  it("indents a custom-only union under its heading", () => {
    expect(renderOnlyACustomDomain()).toContain(ONLY_A_CUSTOM_DOMAIN_ALIASES)
  })
})

/** One catalogue skill, one in the declared `local` category, and one the catalogue lacks. */
const LOCAL_AND_ABSENT_CATALOGUE = buildCatalog(
  {
    "web-styling": buildCatalogCategory({
      displayName: "Styling",
      domain: "web",
    }),
    local: buildCatalogCategory({ displayName: "Local" }),
  },
  [
    buildCatalogSkill("web-styling-tailwind", {
      displayName: "Tailwind",
      category: "web-styling",
    }),
    buildCatalogSkill("meta-design-expressive-typescript", {
      displayName: "Mine",
      category: "local",
    }),
  ]
)

const LOCAL_AND_ABSENT_CONFIG = buildProjectConfig({
  agents: [],
  skills: [
    buildSkillConfig("web-styling-tailwind", { scope: "project" }),
    buildSkillConfig("meta-design-expressive-typescript", { scope: "project" }),
    buildSkillConfig("web-framework-react", { scope: "project" }),
  ],
})

describe("the categories a config narrows to", () => {
  it("are its skills' own, leaving out the local pseudo-category and a skill the catalogue lacks", () => {
    expect(
      generateConfigTypesSource(
        LOCAL_AND_ABSENT_CATALOGUE,
        [],
        [],
        undefined,
        LOCAL_AND_ABSENT_CONFIG
      )
    ).toContain(
      "\nexport type Domain = 'web'\n\nexport type Category = 'web-styling'\n"
    )
  })
})

describe("the domains of a whole catalogue", () => {
  it("sort the extra ones a caller adds", () => {
    expect(
      generateConfigTypesSource(LOCAL_AND_ABSENT_CATALOGUE, [], [], {
        extraDomains: ["zeta", "acme"],
      })
    ).toContain(
      "\nexport type Domain =\n  // Custom\n  | 'acme'\n  | 'zeta'\n  // Marketplace\n  | 'web'\n"
    )
  })
})

describe("a union too wide for its line", () => {
  it("moves to an indented line of its own while that line fits", () => {
    expect(generateConfigTypesSource(THREE_TESTING_SKILLS, [])).toContain(
      THREE_TESTING_SKILLS_ALIAS
    )
  })

  it("stacks one member per line once it fits nowhere", () => {
    expect(generateConfigTypesSource(FOUR_TESTING_SKILLS, [])).toContain(
      FOUR_TESTING_SKILLS_ALIAS
    )
  })

  it("breaks a stack property's assignment the same two ways", () => {
    expect(generateConfigTypesSource(THREE_TESTING_SKILLS, [])).toContain(
      THREE_TESTING_SKILLS_STACK
    )
    expect(generateConfigTypesSource(FOUR_TESTING_SKILLS, [])).toContain(
      FOUR_TESTING_SKILLS_STACK
    )
  })
})

describe("the types of a project that extends its global types", () => {
  it("extends each global union with the project's own, sorted", () => {
    expect(renderProjectTypes()).toContain(PROJECT_TYPES_ALIASES)
  })

  it("re-exports each global union unchanged when the project adds nothing", () => {
    expect(renderBareProjectTypes()).toContain(BARE_PROJECT_TYPES_ALIASES)
  })

  it("keeps the loose stack type", () => {
    expect(renderProjectTypes()).toContain(LOOSE_STACK)
  })
})


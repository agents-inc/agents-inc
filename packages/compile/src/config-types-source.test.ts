/**
 * The type aliases an install's `config-types.ts` narrows `config.ts` with, against catalogues
 * small enough to read. Each spec pins the aliases its branch writes; the interface blocks every
 * file shares are the emission scenarios' to pin. Every rendered file is held against prettier.
 */

